-- Snowflake SQL deliverable. These statements are provided for execution in a
-- Snowflake account; local Python demo does not require an account.
CREATE DATABASE IF NOT EXISTS SKYPOINTS;
CREATE SCHEMA IF NOT EXISTS SKYPOINTS.PUBLIC;
USE DATABASE SKYPOINTS;
USE SCHEMA PUBLIC;

-- 1. Raw / landing tables
CREATE TABLE IF NOT EXISTS RAW_MEMBER_PROFILE (
  SOURCE_FILE VARCHAR(255), COUNTRY_CODE VARCHAR(5),
  RAW_ROW VARIANT, LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);
CREATE TABLE IF NOT EXISTS RAW_REDEMPTION (
  SOURCE_FILE VARCHAR(255), PAYLOAD VARIANT,
  LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- 2. Common staging table
CREATE TABLE IF NOT EXISTS STG_MEMBER_PROFILE (
  MEMBER_ID VARCHAR(18), MEMBER_NAME VARCHAR(255), ENROLLMENT_DATE DATE,
  LAST_FLIGHT_DATE DATE, TIER_CODE VARCHAR(5), COUNTRY_CODE VARCHAR(5),
  DOB DATE, MEMBER_TYPE VARCHAR(30), AGE NUMBER(3),
  STALE_MEMBER BOOLEAN, SOURCE_FILE VARCHAR(255),
  SOURCE_UPDATED_AT TIMESTAMP_NTZ, LOADED_AT TIMESTAMP_NTZ
);

-- 3. Country-specific target tables
CREATE TABLE IF NOT EXISTS MEMBER_INDIA LIKE STG_MEMBER_PROFILE;
CREATE TABLE IF NOT EXISTS MEMBER_USA LIKE STG_MEMBER_PROFILE;
CREATE TABLE IF NOT EXISTS MEMBER_AUSTRALIA LIKE STG_MEMBER_PROFILE;

-- 4. Flattened redemption transaction table
CREATE TABLE IF NOT EXISTS REDEMPTION_TRANSACTION (
  MEMBER_ID VARCHAR(18), FEED_DATE DATE, TXN_ID VARCHAR(100),
  TXN_DATE DATE, PARTNER VARCHAR(255), MILES_REDEEMED NUMBER(18),
  STATUS VARCHAR(30)
);

-- 5. Derived columns (DOB/flight date can be NULL because optional)
INSERT INTO STG_MEMBER_PROFILE (
  MEMBER_ID, MEMBER_NAME, ENROLLMENT_DATE, LAST_FLIGHT_DATE, TIER_CODE,
  COUNTRY_CODE, DOB, MEMBER_TYPE, AGE, STALE_MEMBER, SOURCE_FILE,
  SOURCE_UPDATED_AT, LOADED_AT
)
SELECT MEMBER_ID, MEMBER_NAME, ENROLLMENT_DATE, LAST_FLIGHT_DATE, TIER_CODE,
       COUNTRY_CODE, DOB, MEMBER_TYPE,
       IFF(DOB IS NULL, NULL,
         DATEDIFF(year, DOB, CURRENT_DATE())
         - IFF(TO_CHAR(CURRENT_DATE(),'MMDD') < TO_CHAR(DOB,'MMDD'), 1, 0)),
       IFF(LAST_FLIGHT_DATE IS NULL, NULL,
         DATEDIFF(day, LAST_FLIGHT_DATE, CURRENT_DATE()) > 90),
       SOURCE_FILE, SOURCE_UPDATED_AT, CURRENT_TIMESTAMP()
FROM NORMALIZED_MEMBER_LANDING;

-- 6. Latest record wins. Requires a globally unique MEMBER_ID and a reliable
-- source-updated timestamp. The supplied workbook IDs repeat between countries,
-- so this cross-country logic must only be enabled after the source confirms
-- global uniqueness. Without that contract, do not infer a member move.
CREATE OR REPLACE TEMP TABLE CURRENT_MEMBER AS
SELECT *
FROM STG_MEMBER_PROFILE
QUALIFY ROW_NUMBER() OVER (
  PARTITION BY MEMBER_ID
  ORDER BY SOURCE_UPDATED_AT DESC NULLS LAST, LOADED_AT DESC
) = 1;

-- 7. Refresh country targets from the canonical latest record.
-- This removes a member from the old country after a confirmed country move.
TRUNCATE TABLE MEMBER_INDIA;
INSERT INTO MEMBER_INDIA SELECT * FROM CURRENT_MEMBER WHERE COUNTRY_CODE = 'IND';

TRUNCATE TABLE MEMBER_USA;
INSERT INTO MEMBER_USA SELECT * FROM CURRENT_MEMBER WHERE COUNTRY_CODE = 'USA';

TRUNCATE TABLE MEMBER_AUSTRALIA;
INSERT INTO MEMBER_AUSTRALIA SELECT * FROM CURRENT_MEMBER WHERE COUNTRY_CODE = 'AUS';

-- 8. Flatten redemption JSON after loading documents into RAW_REDEMPTION.PAYLOAD.
INSERT INTO REDEMPTION_TRANSACTION
SELECT
  PAYLOAD:member_id::VARCHAR,
  TRY_TO_DATE(PAYLOAD:feed_date::VARCHAR, 'YYYYMMDD'),
  R.VALUE:txn_id::VARCHAR,
  TRY_TO_DATE(R.VALUE:txn_date::VARCHAR, 'YYYYMMDD'),
  R.VALUE:partner::VARCHAR,
  R.VALUE:miles_redeemed::NUMBER,
  R.VALUE:status::VARCHAR
FROM RAW_REDEMPTION,
LATERAL FLATTEN(INPUT => PAYLOAD:redemptions) R;

-- 9. Join redemption transactions to the current member profile.
SELECT M.MEMBER_ID, M.MEMBER_NAME, M.COUNTRY_CODE,
       R.TXN_ID, R.TXN_DATE, R.PARTNER, R.MILES_REDEEMED, R.STATUS
FROM REDEMPTION_TRANSACTION R
JOIN CURRENT_MEMBER M ON M.MEMBER_ID = R.MEMBER_ID;

-- Basic quality checks
SELECT MEMBER_ID, COUNT(*) FROM STG_MEMBER_PROFILE
GROUP BY MEMBER_ID HAVING COUNT(*) > 1;

SELECT * FROM STG_MEMBER_PROFILE
WHERE MEMBER_ID IS NULL OR MEMBER_NAME IS NULL OR ENROLLMENT_DATE IS NULL
   OR ENROLLMENT_DATE > CURRENT_DATE()
   OR DOB > CURRENT_DATE()
   OR LAST_FLIGHT_DATE > CURRENT_DATE();
